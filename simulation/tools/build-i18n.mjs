// Turns translator JSON files into importable dictionary modules.
// Usage: node tools/build-i18n.mjs <lang> <dir-with-<lang>-*.json> <strings.json from extract-strings>
// Writes js/i18n/<lang>/<part>.js and js/i18n/<lang>/index.js, and reports
// keys that no longer exist in the source and templates with broken placeholders.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const [lang, inputDir, extractedPath] = process.argv.slice(2);
if (!lang || !inputDir || !extractedPath) {
  process.stderr.write('Usage: node tools/build-i18n.mjs <lang> <input-dir> <strings.json>\n');
  process.exit(1);
}

const OUT = fileURLToPath(new URL(`../js/i18n/${lang}/`, import.meta.url));
const extracted = JSON.parse(readFileSync(extractedPath, 'utf8')).files;
const knownStrings = new Set(Object.values(extracted).flatMap((f) => f.strings));
const knownTemplates = new Set(Object.values(extracted).flatMap((f) => f.templates));

const placeholders = (s) => (s.match(/\{\d+\}/g) || []).sort().join(',');
const fixedText = (s) => s.replace(/\{\d+\}/g, '').replace(/[^A-Za-zÇĞİÖŞÜçğıöşü]/g, '');

// The "extra" part holds hand-written strings for text built at runtime
// (lowercased labels, glued words), so it skips the source check.
function clean(part, dict, report) {
  const strict = part !== 'extra';
  const strings = {};
  for (const [en, tr] of Object.entries(dict.strings || {})) {
    if (typeof tr !== 'string' || !tr.trim() || tr === en) continue;
    if (strict && !knownStrings.has(en)) { report.push(`${part}: unknown string ${JSON.stringify(en.slice(0, 60))}`); continue; }
    strings[en] = tr;
  }
  const templates = [];
  for (const [en, tr] of dict.templates || []) {
    if (typeof tr !== 'string' || tr === en) continue;
    if (strict && !knownTemplates.has(en)) { report.push(`${part}: unknown template ${JSON.stringify(en)}`); continue; }
    if (placeholders(en) !== placeholders(tr)) { report.push(`${part}: placeholder mismatch ${JSON.stringify(en)}`); continue; }
    if (fixedText(en).length < 2) { report.push(`${part}: template too generic ${JSON.stringify(en)}`); continue; }
    templates.push([en, tr]);
  }
  return { strings, templates };
}

mkdirSync(OUT, { recursive: true });
const report = [];
const parts = readdirSync(inputDir)
  .filter((f) => f.startsWith(`${lang}-`) && f.endsWith('.json'))
  .map((f) => f.slice(lang.length + 1, -'.json'.length))
  .sort();

let total = 0;
for (const part of parts) {
  const dict = clean(part, JSON.parse(readFileSync(join(inputDir, `${lang}-${part}.json`), 'utf8')), report);
  total += Object.keys(dict.strings).length + dict.templates.length;
  writeFileSync(join(OUT, `${part}.js`),
    `// Generated by tools/build-i18n.mjs — ${lang} strings for the "${part}" area.\n`
    + `// Keys are the English source strings; edit the translations, keep the keys.\nexport default ${JSON.stringify(dict, null, 1)};\n`);
}

const imports = parts.map((p, i) => `import p${i} from './${p}.js';`).join('\n');
writeFileSync(join(OUT, 'index.js'),
  `// Generated by tools/build-i18n.mjs. All ${lang} dictionaries, registered in this order.\n${imports}\n\n`
  + `export default [${parts.map((_, i) => `p${i}`).join(', ')}];\n`);

process.stdout.write(`${parts.length} parts, ${total} entries\n${report.join('\n')}\n`);
